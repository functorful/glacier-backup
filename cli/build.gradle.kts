// 64K image pages run on both 4K and 64K kernels; the UNAS Pro (linux
// aarch64) kernel uses 64K pages, so a default 4K-page image fails there with
// "Failed to create the main Isolate (code 24)". Only needed when building on
// linux/aarch64: that is the only target with 64K-page kernels we support, and
// we do not rely on the flag being accepted on other platforms.
val hostArch: String = System.getProperty("os.arch")
val hostOs: String = System.getProperty("os.name")
val needs64kPages = hostOs.equals("Linux", ignoreCase = true) && (hostArch == "aarch64" || hostArch == "arm64")

graalvmNative {
    binaries.named("main") {
        imageName.set("glacier-backup")
        buildArgs.addAll(
            "--no-fallback",
            "-march=compatibility",
            "--initialize-at-build-time=org.yaml.snakeyaml",
        )
        if (needs64kPages) {
            buildArgs.addAll(
                "-H:+UnlockExperimentalVMOptions",
                "-H:PageSize=65536",
            )
        }
    }
}

