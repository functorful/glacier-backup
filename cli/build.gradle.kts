// The version is stamped verbatim: release builds get -Pversion=X.Y.Z from CI
// (so they print "glacier-backup X.Y.Z"), local builds print the
// 0.0.0-SNAPSHOT default from gradle.properties.
val toolVersion: String = project.version.toString()

val generateVersionSource by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/sources/version/java/main")
    inputs.property("toolVersion", toolVersion)
    outputs.dir(outputDir)
    doLast {
        val packageDir = outputDir.get().dir("com/functorful/glacierbackup/cli").asFile
        packageDir.mkdirs()
        packageDir.resolve("BuildVersion.java").writeText(
            """
            package com.functorful.glacierbackup.cli;

            /** Generated by :cli:generateVersionSource. Do not edit. */
            final class BuildVersion {

                static final String VERSION = "$toolVersion";

                private BuildVersion() {
                }
            }
            """.trimIndent() + "\n",
        )
    }
}

sourceSets.main {
    java.srcDir(generateVersionSource)
}
